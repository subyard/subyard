#!/usr/bin/env python3
"""Generate Veranda's vocabulary from its vendored Yard RPC contract."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent


def identifier(name, entry):
    return entry.get("ident", "".join(part.capitalize() for part in re.split(r"[._-]", name)))


def generate(manifest):
    lines = ["// Generated by veranda/dev/generate-vocabulary.py; DO NOT EDIT.",
             "// These enums describe known vocabulary, never wire deserialization types.",
             f'pub const PROTOCOL_VERSION: u32 = {manifest["rpcVersion"]};',
             f'pub const CONTRACT_REVISION: u32 = {manifest["revision"]};']
    for kind, section in [("ErrorCode", "errorCodes"), ("Capability", "capabilities"),
                          ("Method", "methods"), ("EventName", "events")]:
        entries = manifest[section]
        names = [identifier(name, entry) for name, entry in entries.items()]
        if len(names) != len(set(names)) or any(not re.fullmatch(r"[A-Z][A-Za-z0-9]*", n) for n in names):
            raise ValueError(f"invalid or colliding identifiers in {section}; set explicit ident")
        lines += ["#[derive(Clone, Copy, Debug, PartialEq, Eq)]", f"pub enum {kind} {{"]
        lines += [f"{name}," for name in names]
        lines += ["}", f"impl {kind} {{", "pub const ALL: &'static [Self] = &["]
        lines += [f"Self::{name}," for name in names]
        lines += ["];", "pub const fn as_str(self) -> &'static str {", "match self {"]
        lines += [f'Self::{identifier(name, entry)} => {json.dumps(name)},' for name, entry in entries.items()]
        lines += ["}", "}", "pub fn parse(value: &str) -> Option<Self> {", "match value {"]
        lines += [f'{json.dumps(name)} => Some(Self::{identifier(name, entry)}),' for name, entry in entries.items()]
        lines += ["_ => None,", "}", "}"]
        if kind == "ErrorCode":
            gates = [f'Self::{identifier(name, entry)}' for name, entry in entries.items()
                     if entry.get("group") == "release-gate"]
            lines += ["pub fn is_release_gate(self) -> bool {", "matches!(self, " + " | ".join(gates) + ")", "}"]
        lines += ["}"]
    return subprocess.run(["rustfmt", "+stable", "--edition", "2021", "--emit", "stdout"],
                          input="\n".join(lines) + "\n", text=True,
                          capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--manifest", type=Path, default=ROOT / "contract/yard-rpc/v1/vocabulary.json")
    args = parser.parse_args()
    result = generate(json.loads(args.manifest.read_text()))
    output = ROOT / "client/src/vocabulary.rs"
    if args.check:
        if not output.exists() or output.read_text() != result:
            print("Rust RPC vocabulary is stale; run python3 veranda/dev/generate-vocabulary.py", file=sys.stderr)
            return 1
    else:
        output.write_text(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
