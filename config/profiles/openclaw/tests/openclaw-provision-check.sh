#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../../" && pwd)"
HOOK="$ROOT/config/profiles/openclaw/provision.sh"
tmp="$(mktemp -d /tmp/subyard-openclaw-provision.XXXXXX)"
trap 'rm -rf -- "$tmp"' EXIT
test_root="$tmp/root"
dev_home="$tmp/home"

# Exercise the production extraction command against a disposable prefix. Archive
# directory ownership is foreign; host-free coverage proves metadata preservation,
# while the owning VM lane verifies root extraction and the generic guest guard.
archive_root="$tmp/node-archive"
node_prefix="$tmp/node-prefix"
mkdir -p "$archive_root" "$node_prefix"/{bin,lib,include,share}
chmod 0750 "$node_prefix"/{bin,lib,include,share}
for directory in bin lib include share; do
  printf 'retained %s\n' "$directory" > "$node_prefix/$directory/retained"
done
python3 - "$archive_root/node-fixture.tar.xz" <<'NODE_ARCHIVE'
import io, sys, tarfile
with tarfile.open(sys.argv[1], 'w:xz') as archive:
    for name in ('bin', 'lib', 'include', 'share', 'lib/node_modules'):
        member = tarfile.TarInfo('node-fixture/' + name)
        member.type = tarfile.DIRTYPE
        member.mode = 0o777
        member.uid, member.gid = 424242, 424243
        archive.addfile(member)
    member = tarfile.TarInfo('node-fixture/lib/node_modules/fixture.txt')
    member.uid, member.gid, member.mode = 424242, 424243, 0o644
    payload = b'installed fixture\n'
    member.size = len(payload)
    archive.addfile(member, io.BytesIO(payload))
NODE_ARCHIVE
node_extract="$(awk '/^  tar -xJf / && / -C \/usr\/local --strip-components=1/ {
  sub(/-C \/usr\/local/, "-C \"$target_prefix\""); print; found++
} END { if (found != 1) exit 1 }' "$HOOK")"
prefix_before="$(stat -c '%u:%g:%a:%i' "$node_prefix"/{bin,lib,include,share})"
for extraction in first repeat; do
  tmp="$archive_root" base=node-fixture target_prefix="$node_prefix" bash -c "$node_extract"
  prefix_after="$(stat -c '%u:%g:%a:%i' "$node_prefix"/{bin,lib,include,share})"
  [ "$prefix_before" = "$prefix_after" ] \
    || { printf 'FAIL: %s Node extraction changed existing prefix metadata\n' "$extraction" >&2; exit 1; }
  for directory in bin lib include share; do
    printf 'retained %s\n' "$directory" | cmp -s - "$node_prefix/$directory/retained" \
      || { printf 'FAIL: Node extraction changed retained content\n' >&2; exit 1; }
  done
  printf 'installed fixture\n' | cmp -s - "$node_prefix/lib/node_modules/fixture.txt" \
    || { printf 'FAIL: Node extraction did not install its payload\n' >&2; exit 1; }
done
printf 'ok: Node extraction preserves existing prefix metadata and contents (first/repeat; root ownership requires VM)\n'

mkdir -p "$test_root/usr/local/bin" "$test_root/opt/venv/bin" \
  "$test_root/srv/cache/pnpm" "$test_root/srv/cache/pip" "$test_root/srv/cache/npm" "$test_root/srv/cache/playwright" \
  "$test_root/etc/profile.d" "$test_root/etc/subyard" "$dev_home/.config/pip"

cat > "$test_root/usr/local/bin/node" <<'NODE'
#!/usr/bin/env bash
printf 'v24.15.0\n'
NODE
cat > "$test_root/usr/local/bin/corepack" <<'COREPACK'
#!/usr/bin/env bash
case "${1:-}" in
  --version) printf '0.31.0\n' ;;
  pnpm@11.2.2) printf '11.2.2\n' ;;
  *) printf 'FAIL: unpinned or unexpected package manager\n' >&2; exit 1 ;;
esac
COREPACK
# shellcheck disable=SC1090
. <(awk '/^render_browser_policy\(\) \{/ { render=1 } render { print } render && /^\}$/ { exit }' "$HOOK")
# Use the actual renderer without running the root-only provision entry point.
awk '/^render_pnpm_wrapper\(\) \{/ { render=1 } render { print } render && /^\}$/ { exit }' \
  "$HOOK" > "$tmp/render.sh"
# shellcheck disable=SC1091
. "$tmp/render.sh"
CACHE_PNPM_STORE=/srv/cache/pnpm PNPM_VERSION=11.2.2 \
  render_pnpm_wrapper > "$test_root/usr/local/bin/pnpm"
cp "$ROOT/config/profiles/openclaw/cache/sy-cache.sh" "$test_root/usr/local/bin/sy-cache"
: > "$test_root/srv/cache/.sy-cache.lock"
chmod 0644 "$test_root/srv/cache/.sy-cache.lock"
for entry in npm npx; do
  # shellcheck disable=SC1090
  . <(awk '/^render_npm_wrapper\(\) \{/ { render=1 } render { print } render && /^\}$/ { exit }' "$HOOK")
  render_npm_wrapper "/usr/local/lib/node_modules/npm/bin/$entry-cli.js" > "$test_root/usr/local/bin/$entry"
done
site_dir="$test_root/opt/venv/lib/python/site-packages"
mkdir -p "$site_dir"
cp "$ROOT/config/profiles/openclaw/cache/subyard_cache.py" "$site_dir/"
printf 'import subyard_cache\n' > "$site_dir/subyard_cache.pth"
printf '%s\n' /srv/cache/pip > "$site_dir/subyard_cache_root"
cat > "$test_root/opt/venv/bin/python" <<PYTHON
#!/usr/bin/env bash
printf '%s\\n' '$site_dir'
PYTHON
cat > "$test_root/opt/venv/bin/pip" <<'PIP'
#!/usr/bin/env bash
exit 0
PIP
chmod +x "$test_root/usr/local/bin/"* "$test_root/opt/venv/bin/"*

cat > "$dev_home/.npmrc" <<'NPMRC'
# >>> subyard-openclaw >>>
cache=/srv/cache/npm
# <<< subyard-openclaw <<<
NPMRC
cat > "$dev_home/.config/pip/pip.conf" <<'PIPCONF'
# GENERATED by Subyard openclaw provision.sh — shared pip cache.
[global]
cache-dir = /srv/cache/pip
PIPCONF
printf 'export SUBYARD_OPENCLAW_DOCS=/etc/subyard/openclaw-l1.md\n' \
  > "$test_root/etc/profile.d/subyard-openclaw.sh"
cat > "$test_root/etc/environment" <<'ENVIRONMENT'
# >>> subyard-openclaw >>>
SUBYARD_OPENCLAW_DOCS=/etc/subyard/openclaw-l1.md
# <<< subyard-openclaw <<<
ENVIRONMENT
cp "$ROOT/config/profiles/openclaw/openclaw-l1.md" "$test_root/etc/subyard/openclaw-l1.md"

common_env=(
  PATH="$test_root/usr/local/bin:$PATH"
  OPENCLAW_TEST_ROOT="$test_root"
  OPENCLAW_DEV_HOME="$dev_home"
  OPENCLAW_TEST_ALLOW_NON_ROOT=1
  DEV_USER="$(id -un)"
  PIP_CACHE_DIR=/srv/cache/pip
  npm_config_cache=/srv/cache/npm
  npm_config_store_dir=/srv/cache/pnpm
)

before="$(find "$tmp" -type f -exec sha256sum {} + | sort | sha256sum)"
env "${common_env[@]}" bash "$HOOK" --check >/dev/null
after="$(find "$tmp" -type f -exec sha256sum {} + | sort | sha256sum)"
[ "$before" = "$after" ] || { printf 'FAIL: OpenClaw check mutated state\n' >&2; exit 1; }

# Captured non-default roots must converge with both the hook default and pip.conf.
custom_pip="$tmp/custom pip cache"
printf '%s\n' "$custom_pip" > "$site_dir/subyard_cache_root"
printf '[global]\ncache-dir = %s\n' "$custom_pip" > "$dev_home/.config/pip/pip.conf"
env "${common_env[@]}" PIP_CACHE_DIR="$custom_pip" bash "$HOOK" --check >/dev/null
printf '%s\n' /srv/cache/pip > "$site_dir/subyard_cache_root"
set +e
env "${common_env[@]}" PIP_CACHE_DIR="$custom_pip" bash "$HOOK" --check >/dev/null
status=$?
set -e
[ "$status" -eq 10 ] || { printf 'FAIL: stale pip hook root status=%s, want 10\n' "$status" >&2; exit 1; }
printf '[global]\ncache-dir = /srv/cache/pip\n' > "$dev_home/.config/pip/pip.conf"

printf '\nStale onboarding instructions.\n' >> "$test_root/etc/subyard/openclaw-l1.md"
set +e
env "${common_env[@]}" bash "$HOOK" --check >/dev/null
status=$?
set -e
[ "$status" -eq 10 ] || { printf 'FAIL: stale OpenClaw docs status=%s, want 10\n' "$status" >&2; exit 1; }
cp "$ROOT/config/profiles/openclaw/openclaw-l1.md" "$test_root/etc/subyard/openclaw-l1.md"

cp "$test_root/usr/local/bin/pnpm" "$tmp/current-pnpm"
sed -i 's/corepack "pnpm@$pnpm_version"/corepack pnpm/' "$test_root/usr/local/bin/pnpm"
set +e
env "${common_env[@]}" bash "$HOOK" --check >/dev/null
status=$?
set -e
[ "$status" -eq 10 ] || { printf 'FAIL: unpinned pnpm status=%s, want 10\n' "$status" >&2; exit 1; }
cp "$tmp/current-pnpm" "$test_root/usr/local/bin/pnpm"

sed -i 's/v24\.15\.0/v0.0.0/' "$test_root/usr/local/bin/node"
set +e
env "${common_env[@]}" bash "$HOOK" --check >/dev/null
status=$?
set -e
[ "$status" -eq 10 ] || { printf 'FAIL: OpenClaw drift status=%s, want 10\n' "$status" >&2; exit 1; }

sed -i 's/v0\.0\.0/v24.15.0/' "$test_root/usr/local/bin/node"
env "${common_env[@]}" bash "$HOOK" --check >/dev/null
cp "$test_root/usr/local/bin/sy-cache" "$tmp/cache-current"
printf '\n# stale helper\n' >> "$test_root/usr/local/bin/sy-cache"
set +e
env "${common_env[@]}" bash "$HOOK" --check >/dev/null
status=$?
set -e
[ "$status" -eq 10 ] || { printf 'FAIL: stale cache helper status=%s\n' "$status" >&2; exit 1; }
cp "$tmp/cache-current" "$test_root/usr/local/bin/sy-cache"

printf 'ok: OpenClaw provision check\n'
