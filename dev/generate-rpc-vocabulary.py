#!/usr/bin/env python3
"""Generate the Go Yard RPC vocabulary; DTOs remain handwritten."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent


def identifier(name, entry):
    return entry.get("ident", "".join(part.capitalize() for part in re.split(r"[._-]", name)))


def generate(manifest):
    lines = ["// Code generated by dev/generate-rpc-vocabulary.py; DO NOT EDIT.",
             "package rpc", "", f'const ProtocolVersion = {manifest["rpcVersion"]}',
             f'const ContractRevision = {manifest["revision"]}', "",
             "type ErrorCode string", "",
             "func (code ErrorCode) Valid() bool {", "switch code {"]
    sections = [("Capability", "capabilities", ""), ("Method", "methods", ""),
                ("Code", "errorCodes", "ErrorCode"), ("Event", "events", "")]
    ids = {}
    for prefix, section, _ in sections:
        names = [identifier(name, entry) for name, entry in manifest[section].items()]
        if len(names) != len(set(names)) or any(not re.fullmatch(r"[A-Z][A-Za-z0-9]*", n) for n in names):
            raise ValueError(f"invalid or colliding identifiers in {section}; set explicit ident")
        ids[section] = {name: prefix + identifier(name, entry)
                        for name, entry in manifest[section].items()}
    lines += ["case " + ", ".join(ids["errorCodes"].values()) + ":", "return true",
              "default:", "return false", "}", "}"]
    for prefix, section, kind in sections:
        lines += ["", "const ("]
        for name in manifest[section]:
            lines.append(f'{ids[section][name]} {kind} = {json.dumps(name)}')
        lines.append(")")
    lines += ["", "// MethodCapabilities returns a fresh method-to-capability set.",
              "func MethodCapabilities() map[string]string {", "return map[string]string {"]
    for name, entry in manifest["methods"].items():
        capability = entry["capability"]
        lines.append(f'{ids["methods"][name]}: {ids["capabilities"][capability]},')
    lines += ["}", "}", "", "// CapabilitiesForSession returns a fresh advertised capability list.",
              "func CapabilitiesForSession(session string) []string {", "switch session {"]
    sessions = sorted({s for entry in manifest["capabilities"].values() for s in entry["sessions"]})
    for session in sessions:
        names = [ids["capabilities"][name] for name, entry in manifest["capabilities"].items()
                 if session in entry["sessions"]]
        lines += [f'case {json.dumps(session)}:', 'return []string{' + ', '.join(names) + '}']
    lines += ["default:", "return nil", "}", "}", "", "func ErrorCodesForGroup(group string) []ErrorCode {", "switch group {"]
    for group in sorted({e["group"] for e in manifest["errorCodes"].values() if "group" in e}):
        names = [ids["errorCodes"][n] for n, e in manifest["errorCodes"].items() if e.get("group") == group]
        lines += [f'case {json.dumps(group)}:', 'return []ErrorCode{' + ', '.join(names) + '}']
    lines += ["default:", "return nil", "}", "}", ""]
    return subprocess.run(["gofmt"], input="\n".join(lines), text=True,
                          capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--manifest", type=Path, default=ROOT / "api/yard-rpc/v1/vocabulary.json")
    args = parser.parse_args()
    result = generate(json.loads(args.manifest.read_text()))
    output = ROOT / "internal/rpc/vocabulary_gen.go"
    if args.check:
        if not output.exists() or output.read_text() != result:
            print("Go RPC vocabulary is stale; run make rpc-vocabulary", file=sys.stderr)
            return 1
    else:
        output.write_text(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
